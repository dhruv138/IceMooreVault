#!/usr/bin/env python3
"""Compile the whole vault into files a language model can read in one go.

Writes:
  LLM/Icemoor Full Context.md   every note, including the full text of every session.
                                Load this when the model must be able to use everything.
  LLM/Icemoor Core Context.md   every note, but sessions reduced to their header and TL;DR.
                                Only for models whose context window can't hold the full file;
                                it WILL miss details that exist only in session text.
  00 Campaign/Aliases.md        every note's name with its other names and spellings.

Left out, because they can't help a model reason or would repeat what's already there:
  - metadata blocks (each note's header card already shows them)
  - the generated "Session history" boxes (quotes of session text the file already contains)
  - Dataview code, Obsidian comment markers, templates, scripts, canvas files
  - AI Chats/ (earlier chatbot conversations with invented answers; see decisions.md)
  - index pages that only list links (Timeline, People/Places/Quest Index, Dashboard)

Run from anywhere:  python3 scripts/build_llm_context.py
"""
import re
from pathlib import Path

VAULT = Path(__file__).resolve().parent.parent
OUT = VAULT / "LLM"
ENTITY_FOLDERS = ["People", "Places", "Factions", "Quests", "Clues & Mysteries", "Items", "Lore"]
GUIDES = ["00 Campaign/AI Reading Guide.md", "00 Campaign/Contradictions and Uncertainties.md"]
EXTRA = ["Resources/Campaign Setup.md", "Resources/Source Notes.md"]


def tokens(text):
    """Rough token count for English prose with names and markup (about 3.7 characters each)."""
    return round(len(text) / 3.7)


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    return m.group(1) if m else ""


def fm_list(fm, key):
    m = re.search(rf"^{key}:\n((?:\s+- .*\n?)+)", fm, re.M)
    return [x.strip()[2:].strip().strip('"') for x in m.group(1).splitlines()] if m else []


def clean(text, demote=2):
    """Strip metadata, generated history, Obsidian-only markup; demote headings."""
    text = re.sub(r"^---\n.*?\n---\n", "", text, flags=re.S)
    text = re.sub(r"%% session-history:start %%.*?%% session-history:end %%", "", text, flags=re.S)
    text = re.sub(r"^%%.*?%%\s*$\n?", "", text, flags=re.M)          # marker lines
    text = re.sub(r"```dataview.*?```", "", text, flags=re.S)
    text = re.sub(r"^# .*\n", "", text, count=1, flags=re.M)          # title (re-added by caller)
    text = re.sub(r"^(#{2,5}) ", lambda m: "#" * min(6, len(m.group(1)) + demote) + " ", text, flags=re.M)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def session_key(p):
    return int(re.search(r"\d+", p.stem).group())


def session_section(p, core=False):
    raw = p.read_text(encoding="utf-8")
    num = session_key(p)
    if not raw.startswith("---\n"):
        head = f"### Session {num} (raw notes, not yet set up: no recap, header or links)"
        return head + "\n\n" + raw.strip() if not core else head + "\n\n" + raw.strip()
    title = re.search(r"^# (.*)$", raw, re.M).group(1)
    body = clean(raw)
    if core:
        keep = []
        for block in body.split("\n\n"):
            if block.startswith("**Session:**") or block.startswith("> [!summary]"):
                keep.append(block)
        body = "\n\n".join(keep)
    return f"### {title}\n\n{body}"


def entity_section(p):
    return f"### {p.stem}\n\n" + clean(p.read_text(encoding="utf-8"), demote=2)


def build_aliases():
    rows = []
    for folder in ENTITY_FOLDERS:
        for p in sorted((VAULT / folder).glob("*.md")):
            fm = frontmatter(p.read_text(encoding="utf-8"))
            al = [a for a in dict.fromkeys(fm_list(fm, "aliases")) if a.lower() != p.stem.lower()]
            if al:
                rows.append((p.stem, folder, ", ".join(al)))
    lines = ["---", 'title: "Aliases"', "type: guide", "tags:", "  - guide", "  - ai", "---", "# Aliases", "",
             "Every note that goes by more than one name. Generated by `scripts/build_llm_context.py` "
             "from each note's aliases; edit the aliases on the note itself, not here.", "",
             "| Name in the vault | Kind | Also called |", "|---|---|---|"]
    lines += [f"| [[{n}]] | {f} | {a} |" for n, f, a in rows]
    (VAULT / "00 Campaign" / "Aliases.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(rows)


def build(core):
    parts = []
    name = "Icemoor Core Context" if core else "Icemoor Full Context"
    intro = (
        f"# {name}\n\n"
        + ("**This is the reduced version.** Session notes appear only as their one-paragraph recap. "
           "Details that exist only in session text are missing. Use the Full Context file whenever the "
           "model's context window allows.\n\n" if core else
           "The complete Icemoor campaign vault in one file: every session note in full, and every note about "
           "people, places, factions, quests, mysteries, items and lore. Generated by "
           "`scripts/build_llm_context.py`; don't edit it by hand.\n\n")
        + "Read **Part 1** first: it explains how the notes are written and how far each kind of statement "
          "can be trusted.")
    parts.append(intro)

    parts.append("## Part 1: How to read this vault")
    for g in GUIDES:
        p = VAULT / g
        parts.append(f"### {p.stem}\n\n" + clean(p.read_text(encoding="utf-8")))
    parts.append("### Aliases\n\n" + clean((VAULT / "00 Campaign" / "Aliases.md").read_text(encoding="utf-8")))

    parts.append("## Part 2: Campaign setup")
    for e in EXTRA:
        p = VAULT / e
        if p.exists():
            parts.append(f"### {p.stem}\n\n" + clean(p.read_text(encoding="utf-8")))

    parts.append("## Part 3: Notes on people, places, factions, quests, mysteries, items and lore")
    for folder in ENTITY_FOLDERS:
        parts.append(f"## {folder}")
        parts += [entity_section(p) for p in sorted((VAULT / folder).glob("*.md"))]

    parts.append("## Part 4: Session notes, in order of play")
    parts += [session_section(p, core) for p in sorted((VAULT / "Sessions").glob("*.md"), key=session_key)]

    text = "\n\n".join(parts) + "\n"
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.md").write_text(text, encoding="utf-8")
    return name, tokens(text)


def main():
    n_alias = build_aliases()
    results = [build(core=False), build(core=True)]
    print(f"  Aliases: {n_alias} notes with other names")
    for name, t in results:
        print(f"  {name}: about {t:,} tokens")
    return dict(results)


if __name__ == "__main__":
    main()
